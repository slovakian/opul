#!/usr/bin/env bash
set -euo pipefail

# Maximum allowed tokens per file (Tokens = bytes / 4)
MAX_TOKENS=5000
MAX_BYTES=$((MAX_TOKENS * 4)) # 20,000 bytes

FAILED=0

# Get all added, copied, modified, or renamed files staged for commit
STAGED_FILES=$(git diff --cached --name-only --diff-filter=ACMR)

if [[ -z "$STAGED_FILES" ]]; then
  exit 0
fi

is_ignored_file() {
  local file="$1"

  # Ignore lockfiles
  case "$file" in
    *Cargo.lock|*package-lock.json|*pnpm-lock.yaml|*yarn.lock|*bun.lock*|*skills-lock.json|*.lock)
      return 0
      ;;
  esac

  # Ignore media / binaries / fonts / assets
  case "$file" in
    *.png|*.jpg|*.jpeg|*.gif|*.ico|*.icns|*.webp|*.svg|*.pdf|*.zip|*.tar|*.gz|*.dmg|*.woff|*.woff2|*.ttf|*.eot|*.mp4|*.mov|*.webm|*.mp3|*.wav|frontend/assets/*|*/frontend/assets/*)
      return 0
      ;;
  esac

  # Ignore vendored files, node_modules, target, git hooks internal dispatcher, and agent skills
  case "$file" in
    node_modules/*|*/node_modules/*|target/*|*/target/*|.vite-hooks/_/*|*/vendor/*|vendor/*|.agents/*|*/.agents/*)
      return 0
      ;;
  esac

  # Ignore codegen files by path pattern
  case "$file" in
    *.gen.*|*.generated.*|*__generated__*|*codegen*|*/codegen/*)
      return 0
      ;;
  esac

  # Check if file still exists on disk
  if [[ ! -f "$file" ]]; then
    return 0
  fi

  # Check if file contains codegen / generated markers in first 20 lines
  if head -n 20 "$file" 2>/dev/null | grep -Eq '@generated|DO NOT EDIT|This file is generated|Code generated by|Auto-generated by'; then
    return 0
  fi

  return 1
}

while IFS= read -r file; do
  [[ -z "$file" ]] && continue

  if is_ignored_file "$file"; then
    continue
  fi

  if [[ ! -f "$file" ]]; then
    continue
  fi

  # Determine file size in bytes
  if [[ "$(uname)" == "Darwin" ]]; then
    BYTES=$(stat -f%z "$file" 2>/dev/null || wc -c < "$file")
  else
    BYTES=$(stat -c%s "$file" 2>/dev/null || wc -c < "$file")
  fi

  # Strip any whitespace
  BYTES=$(echo "$BYTES" | tr -d ' ')
  TOKENS=$(( BYTES / 4 ))

  if [[ "$TOKENS" -gt "$MAX_TOKENS" ]]; then
    FAILED=1
    cat >&2 <<EOF

================================================================================
🚫 COMMIT REJECTED: FILE EXCEEDS 5,000 TOKENS (bytes/4)
================================================================================
File:      $file
Size:      $BYTES bytes (~$TOKENS tokens)
Limit:     $MAX_BYTES bytes ($MAX_TOKENS tokens)

Files authored by agents must stay under 5,000 tokens for optimal processing,
readability, modularity, and context window efficiency.

--------------------------------------------------------------------------------
HOW TO SPLIT THIS FILE:
--------------------------------------------------------------------------------

1. Identify Distinct Responsibilities:
   • Scan $file for self-contained components, helpers, types, or subroutines.
   • Separate data models/interfaces, UI presentation, and state/business logic.

2. Extract into Focused Modules:
   • TypeScript / React:
     - Move interfaces and types to a separate \`*.types.ts\` or \`model.ts\`.
     - Extract child components into dedicated files in a \`components/\` subfolder.
     - Move business logic and stateful hooks to \`hooks/use-*.ts\` or \`lib/*.ts\`.
     - Extract pure utilities and formatting functions into \`lib/utils.ts\`.
   • Rust:
     - Decompose large \`*.rs\` files into a directory module (e.g. \`module/mod.rs\`).
     - Split domain structs, traits, and implementations across \`module/types.rs\`,
       \`module/handlers.rs\`, etc.
     - Use \`pub use ...\` in \`mod.rs\` to preserve the public API surface.
   • Other files (CSS, JSON, Config):
     - Break large configurations into partial imports or composed objects.

3. Update Imports & Verify:
   • Import the newly extracted files back into $file.
   • Verify the split files each stay well under 5,000 tokens ($MAX_BYTES bytes).
   • Run project checks:
       vp check
       npm test
       cargo test --workspace

4. Stage and Commit:
   • Stage all changed and newly created files:
       git add $file <newly-extracted-files>
   • Retry your commit.

================================================================================
EOF
  fi
done <<< "$STAGED_FILES"

if [[ "$FAILED" -ne 0 ]]; then
  exit 1
fi

exit 0
